"""Public appearance assets; no credentials, executable config or privileged writes."""
import configparser
import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

IMAGES = {'.png', '.jpg', '.jpeg', '.webp', '.bmp'}
VIDEOS = {'.mp4', '.webm', '.mkv', '.mov', '.m4v'}

def asset_path(value, backgrounds):
    path = Path(value).expanduser()
    if not path.is_absolute():
        if '..' in path.parts:
            raise ValueError('wallpaper path must not escape backgrounds')
        path = Path(backgrounds) / path
    path = path.resolve()
    if not path.is_file() or any(c in str(path) for c in '\n\r\x00'):
        raise ValueError('missing or invalid wallpaper: ' + str(path))
    return path

def preset_assets(preset, backgrounds):
    home = asset_path(preset['wallpaper'], backgrounds)
    lock = asset_path(preset.get('lockWallpaper', preset['wallpaper']), backgrounds)
    if home.suffix.lower() not in IMAGES | VIDEOS | {'.gif'}:
        raise ValueError('unsupported home wallpaper format')
    if lock.suffix.lower() not in IMAGES:
        raise ValueError('lockWallpaper must be a static image (required for video/GIF home wallpaper)')
    return home, lock

def palette_colors(source):
    result = subprocess.run(['jeebis-theme-colors', '--file', str(source), '--all'],
                            check=True, text=True, stdout=subprocess.PIPE)
    colors = dict(line.split('\t', 1) for line in result.stdout.splitlines() if '\t' in line)
    for key in ['background', 'foreground', 'accent', 'selection_background', 'selection_foreground', 'lighter_background', 'muted']:
        if not re.fullmatch(r'#[0-9a-fA-F]{6}', colors.get(key, '')):
            raise ValueError('invalid resolved color: ' + key)
    return colors

def write_assets(target, colors, lock):
    target.mkdir(parents=True, exist_ok=True)
    c = colors
    shutil.copyfile(lock, target / ('lock-wallpaper' + lock.suffix.lower()))
    os.symlink('lock-wallpaper' + lock.suffix.lower(), target / 'lock-wallpaper')
    names = {
        'window_bg_color': 'background', 'window_fg_color': 'foreground',
        'view_bg_color': 'background', 'view_fg_color': 'foreground',
        'headerbar_bg_color': 'lighter_background', 'headerbar_fg_color': 'foreground',
        'card_bg_color': 'lighter_background', 'card_fg_color': 'foreground',
        'popover_bg_color': 'background', 'popover_fg_color': 'foreground',
        'dialog_bg_color': 'background', 'dialog_fg_color': 'foreground',
        'accent_bg_color': 'selection_background', 'accent_fg_color': 'selection_foreground',
        'accent_color': 'accent', 'theme_bg_color': 'background', 'theme_fg_color': 'foreground',
        'theme_base_color': 'background', 'theme_text_color': 'foreground',
        'theme_selected_bg_color': 'selection_background', 'theme_selected_fg_color': 'selection_foreground',
        'borders': 'muted', 'sidebar_bg_color': 'lighter_background', 'sidebar_fg_color': 'foreground',
    }
    (target / 'gtk.css').write_text('/* Generated by jeebis-desktop theme. */\n' + ''.join(
        '@define-color ' + name + ' ' + c[key] + ';\n' for name, key in names.items()))
    # QPalette roles 0..21; Qt5 ignores the final Qt6 Accent role.
    roles = ['foreground', 'lighter_background', 'foreground', 'foreground', 'muted', 'muted',
             'foreground', 'foreground', 'foreground', 'background', 'background', 'muted',
             'selection_background', 'selection_foreground', 'accent', 'accent', 'lighter_background',
             'muted', 'background', 'foreground', 'muted', 'accent']
    active = ', '.join('#ff' + c[key][1:] for key in roles)
    disabled = ', '.join('#ff' + c['muted' if key == 'foreground' else key][1:] for key in roles)
    (target / 'qt.colors').write_text('[ColorScheme]\nactive_colors=' + active + '\ninactive_colors=' + active + '\ndisabled_colors=' + disabled + '\n')
    config = configparser.ConfigParser(); config.optionxform = str
    config['General'] = {'Background': 'Backgrounds/jeebis', 'BackgroundColor': c['background'],
        'FormBackgroundColor': c['background'], 'DimBackgroundColor': c['background'],
        'LoginFieldBackgroundColor': c['lighter_background'], 'PasswordFieldBackgroundColor': c['lighter_background'],
        'LoginButtonBackgroundColor': c['selection_background'], 'LoginButtonTextColor': c['selection_foreground'],
        **{key: c['foreground'] for key in ['HeaderTextColor', 'DateTextColor', 'TimeTextColor',
            'LoginFieldTextColor', 'PasswordFieldTextColor', 'UserIconColor', 'PasswordIconColor',
            'SystemButtonsIconsColor', 'SessionButtonTextColor']}}
    with (target / 'sddm.conf').open('w') as stream:
        config.write(stream)
    for file in target.iterdir():
        if not file.is_symlink(): file.chmod(0o644)
    target.chmod(0o755)

def publish(root, colors, lock, metadata):
    root = Path(root); root.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix='.appearance-', dir=root))
    try:
        write_assets(staging, colors, lock)
        (staging / 'preset.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
        (staging / 'preset.json').chmod(0o644)
        old = (root / 'current').resolve() if (root / 'current').is_symlink() else None
        link = root / '.current-next'; link.unlink(missing_ok=True)
        link.symlink_to(staging.name); link.replace(root / 'current')
        # Keep only this generation and its immediate predecessor for in-flight readers.
        for path in root.glob('.appearance-*'):
            if path.is_dir() and path not in (staging, old): shutil.rmtree(path)
    except BaseException:
        if (root / 'current').resolve() != staging: shutil.rmtree(staging, ignore_errors=True)
        raise
